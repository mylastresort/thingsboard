#!/usr/bin/env bash
# benchmark-builds.sh — Compare --no-cache build times before and after cache optimization.
# Usage: ./scripts/benchmark-builds.sh [iterations]
#
# Requires: docker, make, git, time (bash built-in)
# Run from repo root.

set -euo pipefail

ITERATIONS=${1:-3}
RESULTS_DIR="./benchmark-results"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
RESULTS_FILE="${RESULTS_DIR}/build-bench-${TIMESTAMP}.md"

# Services to benchmark (only the ones we changed)
SERVICES=(
  "tb-python-tools"
  "pdm-forecast-worker"
  "pdm-anomaly-worker"
  "pdm-model-store"
  "thingsboard-mcp"
  "go-toolbox-interpreter"
  "go-toolbox-darktheme"
  "tb-quarkus-cmd-dev"
  "ai-agent-py"
  "config-api"
  "pandas-mcp"
  "ws-events"
)

mkdir -p "$RESULTS_DIR"

echo "# Docker Build Benchmark — ${TIMESTAMP}" > "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"
echo "Iterations per service: **${ITERATIONS}**" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"

# ─── Helper: build a single service N times, return mean wall-clock seconds ───
bench_service() {
  local svc=$1
  local total=0
  local ok=0
  for ((i=1; i<=ITERATIONS; i++)); do
    local start end elapsed
    start=$(date +%s%N)
    if docker compose build --no-cache "$svc" >/dev/null 2>&1; then
      end=$(date +%s%N)
      elapsed=$(( (end - start) / 1000000 ))  # ms
      total=$((total + elapsed))
      ok=$((ok + 1))
    else
      echo "  [WARN] $svc build failed on iteration $i" >&2
    fi
  done
  if [ "$ok" -gt 0 ]; then
    echo $(( total / ok ))
  else
    echo "FAIL"
  fi
}

# ─── Benchmark current branch (after) ───
echo "## After (current branch: $(git branch --show-current))" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"
echo "| Service | Mean build time (s) |" >> "$RESULTS_FILE"
echo "|---------|--------------------|" >> "$RESULTS_FILE"

for svc in "${SERVICES[@]}"; do
  printf "  Benchmarking %-30s ..." "$svc"
  result=$(bench_service "$svc")
  if [ "$result" = "FAIL" ]; then
    printf " FAIL\n"
    echo "| $svc | FAIL |" >> "$RESULTS_FILE"
  else
    secs=$(echo "scale=1; $result / 1000" | bc)
    printf " %ss\n" "$secs"
    echo "| $svc | ${secs} |" >> "$RESULTS_FILE"
  fi
done

# ─── Benchmark previous branch (before) ───
PREV_BRANCH="dev"
CURRENT_BRANCH=$(git branch --show-current)

echo "" >> "$RESULTS_FILE"
echo "## Before (branch: ${PREV_BRANCH})" >> "$RESULTS_FILE"
echo "" >> "$RESULTS_FILE"
echo "| Service | Mean build time (s) |" >> "$RESULTS_FILE"
echo "|---------|--------------------|" >> "$RESULTS_FILE"

# Stash any uncommitted changes, checkout dev, build, return
git stash --include-untracked -q 2>/dev/null || true
git checkout "$PREV_BRANCH" -q

for svc in "${SERVICES[@]}"; do
  printf "  Benchmarking %-30s ..." "$svc"
  result=$(bench_service "$svc")
  if [ "$result" = "FAIL" ]; then
    printf " FAIL\n"
    echo "| $svc | FAIL |" >> "$RESULTS_FILE"
  else
    secs=$(echo "scale=1; $result / 1000" | bc)
    printf " %ss\n" "$secs"
    echo "| $svc | ${secs} |" >> "$RESULTS_FILE"
  fi
done

# Restore working state
git checkout "$CURRENT_BRANCH" -q
git stash pop -q 2>/dev/null || true

echo "" >> "$RESULTS_FILE"
echo "---" >> "$RESULTS_FILE"
echo "Generated by \`scripts/benchmark-builds.sh\`" >> "$RESULTS_FILE"

echo ""
echo "Results written to: $RESULTS_FILE"
cat "$RESULTS_FILE"
